#!/usr/bin/env bash
# Install or update DefectDojo on the DevSecOps VM. Idempotent: a second run changes nothing.
#   cd ~/smoke-landing && git pull && sudo vm/defectdojo/setup.sh
#
# What it does (in this order, so the port is never reachable from builds, not even briefly):
#   1. copies the compose files + scripts to $DEFECTDOJO_DIR (/opt/defectdojo), owned by smoke
#   2. generates .env (0600) with strong random secrets on first run; refreshes version/port/IP
#   3. installs + starts dojo-firewall.service (builds/scanners can't reach DefectDojo or the metadata server)
#   4. docker compose up (pinned tag); waits for the first-boot migrations
#   5. provisions: product type, non-admin user "smoke-pipeline" + API token -> runner.env,
#      Jira/GitHub integrations off
#   6. installs the nightly backup timer (dojo-backup.timer)
#   7. runs verify-isolation.sh
set -euo pipefail
SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck source=dojo-lib.sh
source "$SRC/dojo-lib.sh"
need_root
command -v docker >/dev/null && docker compose version >/dev/null 2>&1 || die "Docker + compose plugin required (run vm/bootstrap.sh first)"
for c in ss ip curl jq openssl; do command -v "$c" >/dev/null || die "missing command: $c (apt-get install iproute2 curl jq openssl)"; done
id "$DOJO_USER" >/dev/null 2>&1 || die "user $DOJO_USER missing (run vm/bootstrap.sh first)"
PORT="${DEFECTDOJO_PORT:?}"
changed=0

# --- 1. files ------------------------------------------------------------------------------------------
install -d -m 0750 -o "$DOJO_USER" -g "$DOJO_USER" "$DOJO_DIR"
for f in docker-compose.yml docker-compose.iap.yml dojo-lib.sh firewall.sh backup.sh restore.sh upgrade.sh \
         status.sh add-user.sh verify-isolation.sh; do
  if ! cmp -s "$SRC/$f" "$DOJO_DIR/$f"; then
    install -m "$([[ $f == *.sh ]] && echo 0750 || echo 0640)" -o "$DOJO_USER" -g "$DOJO_USER" "$SRC/$f" "$DOJO_DIR/$f"
    changed=1
  fi
done
cfg="$SRC/../../smoke.config.env"
[[ -r "$cfg" ]] || cfg="$SRC/smoke.config.env"
cmp -s "$cfg" "$DOJO_DIR/smoke.config.env" || { install -m 0640 -o "$DOJO_USER" -g "$DOJO_USER" "$cfg" "$DOJO_DIR/smoke.config.env"; changed=1; }

# --- 2. .env ---------------------------------------------------------------------------------------------
if ss -ltnH "( sport = :$PORT )" | grep -q . && ! dc ps --status running nginx 2>/dev/null | grep -q nginx; then
  die "port $PORT is in use by something else: $(ss -ltnpH "( sport = :$PORT )" | head -1)"
fi
if [[ ! -f "$DOJO_ENV" ]]; then
  log "first run: generating secrets in $DOJO_ENV"
  umask 077
  cat > "$DOJO_ENV" <<EOF
# DefectDojo secrets. Generated by setup.sh. Keep a copy in your password manager. Never commit.
COMPOSE_PROJECT_NAME=defectdojo
DD_SECRET_KEY=$(openssl rand -hex 32)
DD_CREDENTIAL_AES_256_KEY=$(openssl rand -hex 16)
DD_DB_PASSWORD=$(openssl rand -hex 24)
DD_ADMIN_PASSWORD=Dd-$(openssl rand -hex 12)
EOF
  changed=1
fi
chown "$DOJO_USER:$DOJO_USER" "$DOJO_ENV"; chmod 0600 "$DOJO_ENV"
ip="$(internal_ip)"
for kv in "DD_VERSION=$DEFECTDOJO_VERSION" "DD_PORT=$PORT" "DD_INTERNAL_IP=$ip" "DD_SITE_URL=$DEFECTDOJO_UI_URL" \
          "DD_BRIDGE=br-dojo" "COMPOSE_FILE=docker-compose.yml:docker-compose.iap.yml"; do
  envset "${kv%%=*}" "${kv#*=}" && changed=1
done

# --- 3. firewall (before anything listens) --------------------------------------------------------------
unit=/etc/systemd/system/dojo-firewall.service
want_unit="[Unit]
Description=Block Docker containers from DefectDojo (tcp/$PORT) and the metadata server
After=docker.service
PartOf=docker.service

[Service]
Type=oneshot
RemainAfterExit=yes
Environment=DD_PORT=$PORT DD_BRIDGE=br-dojo
ExecStart=$DOJO_DIR/firewall.sh apply
ExecStop=$DOJO_DIR/firewall.sh remove

[Install]
WantedBy=docker.service multi-user.target"
if [[ "$(cat "$unit" 2>/dev/null)" != "$want_unit" ]]; then
  echo "$want_unit" > "$unit"; systemctl daemon-reload; changed=1
fi
systemctl enable --quiet dojo-firewall.service
systemctl is-active --quiet dojo-firewall.service || { systemctl start dojo-firewall.service; changed=1; }
[[ $changed == 1 ]] && systemctl restart dojo-firewall.service

# --- 4. start --------------------------------------------------------------------------------------------
log "starting DefectDojo $DEFECTDOJO_VERSION"
for try in 1 2 3; do dc pull -q && break; (( try < 3 )) || die "image pull failed"; sleep $((try * 30)); done
dc up -d --remove-orphans --quiet-pull 2>&1 | grep -vE "Running|Waiting|Healthy|Exited$" || true
wait_dojo 180

# --- 5. provision (inside the app, so it doesn't depend on the admin password, which the operator changes) --
log "provisioning product type '$DEFECTDOJO_PRODUCT_TYPE' and user smoke-pipeline"
out="$(dojo_shell <<PY
from dojo.models import Product_Type, Dojo_User, UserContactInfo
from dojo.system_settings.models import System_Settings
from rest_framework.authtoken.models import Token
pt, _ = Product_Type.objects.get_or_create(name="$DEFECTDOJO_PRODUCT_TYPE",
    defaults={"description": "Apps gated by smoke-landing (https://github.com/TestingRino/smoke-landing)"})
u, created = Dojo_User.objects.get_or_create(username="smoke-pipeline",
    defaults={"first_name": "smoke-landing", "last_name": "pipeline", "email": "smoke-pipeline@localhost"})
if created:
    u.set_unusable_password()   # API token only; can't log in to the UI
u.is_staff = False
u.is_superuser = False
u.save()
pt.authorized_users.add(u)      # import/add/edit under this product type only; no delete, no other types, no config
tok, _ = Token.objects.get_or_create(user=u)
ss = System_Settings.objects.get()
if ss.enable_jira or ss.enable_github:
    ss.enable_jira = False; ss.enable_github = False; ss.save()   # smoke-landing files GitHub issues itself
print("PT_ID=%d" % pt.id)
print("TOKEN=" + tok.key)
PY
)"
token="$(sed -n 's/^TOKEN=//p' <<< "$out")"
[[ "$token" =~ ^[0-9a-f]{40}$ ]] || die "provisioning failed: $(grep -v TOKEN <<< "$out" | tail -5)"

# runner.env: DEFECTDOJO_URL / DEFECTDOJO_TOKEN (other lines untouched; token never printed)
install -d -m 0750 -o root -g "$DOJO_USER" "$(dirname "$RUNNER_ENV")"
touch "$RUNNER_ENV"; chown root:"$DOJO_USER" "$RUNNER_ENV"; chmod 0640 "$RUNNER_ENV"
upd() {
  if grep -qE "^$1=" "$RUNNER_ENV"; then
    [[ "$(grep -E "^$1=" "$RUNNER_ENV" | cut -d= -f2-)" == "$2" ]] && return 0
    sed -i "s|^$1=.*|$1=$2|" "$RUNNER_ENV"
  else echo "$1=$2" >> "$RUNNER_ENV"; fi
  log "runner.env: $1 updated"
}
upd DEFECTDOJO_URL "http://127.0.0.1:$PORT"
upd DEFECTDOJO_TOKEN "$token"

# --- 6. nightly backup --------------------------------------------------------------------------------------
svc="[Unit]
Description=Back up DefectDojo (pg_dump + media) to $BACKUP_DIR and gs://$DEFECTDOJO_BACKUP_BUCKET
After=docker.service

[Service]
Type=oneshot
ExecStart=$DOJO_DIR/backup.sh"
tmr="[Unit]
Description=Nightly DefectDojo backup

[Timer]
OnCalendar=*-*-* 02:37:00 UTC
RandomizedDelaySec=15m
Persistent=true

[Install]
WantedBy=timers.target"
for pair in "dojo-backup.service|$svc" "dojo-backup.timer|$tmr"; do
  f="/etc/systemd/system/${pair%%|*}"
  [[ "$(cat "$f" 2>/dev/null)" == "${pair#*|}" ]] || { echo "${pair#*|}" > "$f"; systemctl daemon-reload; }
done
systemctl enable --quiet --now dojo-backup.timer

# --- 7. verify ---------------------------------------------------------------------------------------------
"$DOJO_DIR/verify-isolation.sh" || warn "isolation check FAILED: see above. Do not open IAP access until it passes."

cat <<EOF

DefectDojo $DEFECTDOJO_VERSION is up: 127.0.0.1:$PORT and $ip:$PORT (IAP only).
  Secrets:          $DOJO_ENV   (store a copy in your password manager)
  Admin password:   sudo grep DD_ADMIN_PASSWORD $DOJO_ENV
                    then log in as 'admin' and change it (top right, user menu -> Change password)
  Pipeline token:   in $RUNNER_ENV as DEFECTDOJO_TOKEN (user smoke-pipeline, product type '$DEFECTDOJO_PRODUCT_TYPE' only)
  Status:           sudo $DOJO_DIR/status.sh
EOF
